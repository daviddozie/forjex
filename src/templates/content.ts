export function getCICDWorkflowContent(framework: string, branch?: string): string {
  const workflow = getDefaultCICDWorkflowContent(framework);
  return branch
    ? workflow.replaceAll('branches: [main, master]', `branches: [${JSON.stringify(branch)}]`)
    : workflow;
}

