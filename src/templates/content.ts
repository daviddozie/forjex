export function getTemplateFiles(framework: string, projectName: string): TemplateFile[] {
  switch (framework) {
    case 'nextjs':
    case 'vite-react':
    case 'react':
    case 'vue':
      return getWebTemplateFiles(framework, projectName);

    case 'python':
    case 'python-fastapi':
      return [
        {
          path: 'requirements.txt',
          content: `fastapi>=0.115.0
uvicorn>=0.32.0
pydantic>=2.10.0
pytest>=8.3.0
httpx>=0.28.0
`,
        },
        {
          path: 'main.py',
          content: `from fastapi import FastAPI

app = FastAPI(title="${projectName}", version="0.1.0")

@app.get("/")
def read_root():
    return {
        "project": "${projectName}",
        "status": "healthy",
        "message": "Bootstrapped with Forjex",
        "docs_url": "/docs"
    }

@app.get("/health")
def health():
    return {"status": "ok"}
`,
        },
        {
          path: 'test_main.py',
          content: `from fastapi.testclient import TestClient
from main import app

client = TestClient(app)

def test_read_root():
    response = client.get("/")
    assert response.status_code == 200
    assert response.json()["status"] == "healthy"

def test_health():
    response = client.get("/health")
    assert response.status_code == 200
    assert response.json()["status"] == "ok"
`,
        },
      ];

    case 'go':
    case 'go-api':
      return [
        {
          path: 'go.mod',
          content: `module ${projectName}

go 1.22
`,
        },
        {
          path: 'main.go',
          content: `package main

import (
	"encoding/json"
	"fmt"
	"net/http"
)

type StatusResponse struct {
	Project string \`json:"project"\`
	Status  string \`json:"status"\`
	Message string \`json:"message"\`
}

func main() {
	http.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(StatusResponse{
			Project: "${projectName}",
			Status:  "healthy",
			Message: "Bootstrapped with Forjex",
		})
	})

	http.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]string{"status": "ok"})
	})

	fmt.Println("Server running on :8080")
	http.ListenAndServe(":8080", nil)
}
`,
        },
        {
          path: 'main_test.go',
          content: `package main

import (
	"net/http"
	"net/http/httptest"
	"testing"
)

func TestHealth(t *testing.T) {
	req, err := http.NewRequest("GET", "/health", nil)
	if err != nil {
		t.Fatal(err)
	}

	rr := httptest.NewRecorder()
	handler := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
		w.Write([]byte(\`{"status":"ok"}\`))
	})

	handler.ServeHTTP(rr, req)

	if status := rr.Code; status != http.StatusOK {
		t.Errorf("handler returned wrong status code: got %v want %v", status, http.StatusOK)
	}
}
`,
        },
      ];

    case 'rust':
    case 'rust-app':
      return [
        {
          path: 'Cargo.toml',
          content: `[package]
name = "${projectName}"
version = "0.1.0"
edition = "2021"

[dependencies]
`,
        },
        {
          path: 'src/main.rs',
          content: `fn main() {
    println!("Hello from ${projectName}, bootstrapped with Forjex!");
}

#[cfg(test)]
mod tests {
    #[test]
    fn it_works() {
        assert_eq!(2 + 2, 4);
    }
}
`,
        },
      ];

    default:
      return [
        {
          path: 'package.json',
          content: JSON.stringify(
            {
              name: projectName,
              version: '0.1.0',
              private: true,
              scripts: {
                start: 'node index.js',
              },
            },
            null,
            2,
          ),
        },
        {
          path: 'index.js',
          content: `console.log("Hello from ${projectName}, bootstrapped with Forjex!");\n`,
        },
      ];
  }
}
